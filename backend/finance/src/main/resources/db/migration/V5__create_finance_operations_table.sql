CREATE TABLE finance_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL REFERENCES finance_categories (id),
    operation_date DATE NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_finance_operations_category_date UNIQUE (category_id, operation_date)
);

CREATE INDEX idx_finance_operations_user_id ON finance_operations (user_id);

CREATE INDEX idx_finance_operations_user_id_date ON finance_operations (user_id, operation_date);
