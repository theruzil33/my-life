CREATE TABLE gateway_refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_gateway_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_gateway_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES gateway_users (id)
);

CREATE INDEX idx_gateway_refresh_tokens_user_id ON gateway_refresh_tokens (user_id);
