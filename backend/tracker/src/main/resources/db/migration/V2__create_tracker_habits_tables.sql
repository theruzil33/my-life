CREATE TABLE tracker_habits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    start_date DATE NOT NULL,
    frequency VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_tracker_habits_user_id ON tracker_habits (user_id);

CREATE TABLE tracker_habit_weekdays (
    habit_id BIGINT NOT NULL,
    day_of_week SMALLINT NOT NULL,
    CONSTRAINT pk_tracker_habit_weekdays PRIMARY KEY (habit_id, day_of_week),
    CONSTRAINT fk_tracker_habit_weekdays_habit FOREIGN KEY (habit_id) REFERENCES tracker_habits (id) ON DELETE CASCADE
);

CREATE TABLE tracker_habit_completions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id BIGINT NOT NULL,
    completed_on DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_tracker_habit_completions_habit_date UNIQUE (habit_id, completed_on),
    CONSTRAINT fk_tracker_habit_completions_habit FOREIGN KEY (habit_id) REFERENCES tracker_habits (id) ON DELETE CASCADE
);
